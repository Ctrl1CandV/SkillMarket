// Click through the event page: spine -> night, pick two nights, fill the form, confirm, cancel one. Desktop and phone.
import { createRequire } from 'node:module'; import path from 'node:path'; import { pathToFileURL } from 'node:url';
const require = createRequire(path.join(process.env.FC_NODE_MODULES, 'x.js')); const { chromium } = require('playwright-core');
const [file, out] = process.argv.slice(2); const url = pathToFileURL(file).href;
const browser = await chromium.launch({ executablePath: process.env.FC_CHROME, headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto(url); await page.waitForTimeout(300);
const over = await page.evaluate(() => [...document.querySelectorAll('text.ttl')].filter(el => el.getBBox().height > +el.dataset.room + 1).length);
console.log('spine titles overflowing:', over);
await page.locator('.spine[data-i="5"]').click(); await page.waitForTimeout(700);
console.log('night highlighted:', await page.locator('.night.on h3').innerText());
await page.screenshot({ path: path.join(out, 'e1-night.png') });
await page.locator('[data-pick="5"]').click(); await page.locator('[data-pick="7"]').click();
console.log('dock:', await page.locator('#dock-text').innerText());
await page.locator('#dock-go').click(); await page.locator('#ok').click();
console.log('errors shown without input:', await page.locator('.field.bad').count());
await page.fill('#name', '周老师'); await page.fill('#phone', '13912345678'); await page.locator('#seats button[data-n="2"]').click();
await page.screenshot({ path: path.join(out, 'e2-form.png') });
await page.locator('#ok').click(); await page.waitForTimeout(200);
console.log('done:', (await page.locator('#dlg-body h2').innerText()));
await page.screenshot({ path: path.join(out, 'e3-done.png') });
await page.locator('#x').click();
console.log('booked buttons:', await page.locator('.pick.booked').count(), '| spines raised:', await page.locator('.spine.on').count());
await page.locator('[data-cancel="7"]').click(); await page.locator('[data-cancel="7"]').click();
console.log('after cancel, booked:', await page.locator('.pick.booked').count());
await page.reload(); console.log('after reload, booked:', await page.locator('.pick.booked').count());
await page.screenshot({ path: path.join(out, 'e4-list.png'), fullPage: true });
const m = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }); await m.goto(url); await m.waitForTimeout(300);
await m.screenshot({ path: path.join(out, 'm1.png'), fullPage: true });
console.log('errors:', errors.length, errors.slice(0, 2)); await browser.close();
