// Drive the bakery flow end to end: order on the phone page, then find and pick it up on the owner page.
import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const require = createRequire(path.join(process.env.FC_NODE_MODULES, 'x.js'));
const { chromium } = require('playwright-core');
const [dir, out] = process.argv.slice(2); fs.mkdirSync(out, { recursive: true });
const url = (f, q = '') => pathToFileURL(path.join(dir, f)).href + q;
const browser = await chromium.launch({ executablePath: process.env.FC_CHROME, headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const page = await ctx.newPage(); const errors = [];
page.on('pageerror', e => errors.push(e.message)); page.on('console', m => m.type() === 'error' && errors.push(m.text()));
await page.goto(url('order.html')); await page.screenshot({ path: path.join(out, 'order-1-first.png') });
await page.screenshot({ path: path.join(out, 'order-1-full.png'), fullPage: true });
await page.locator('.bread[data-id="toast"] .plus').tap();
await page.locator('.bread[data-id="croissant"] .plus').tap(); await page.locator('.bread[data-id="croissant"] .plus').tap();
await page.locator('#submit').tap(); await page.waitForTimeout(500);
await page.screenshot({ path: path.join(out, 'order-2-missing-slot.png') });
await page.locator('input[value="morning"]').check();
await page.locator('#submit').tap(); await page.waitForTimeout(300);
await page.screenshot({ path: path.join(out, 'order-3-missing-name.png') });
await page.fill('#name', '周老师'); await page.fill('#phone', '13912345678');
await page.locator('#add-note').tap(); await page.fill('#note', '吐司帮忙切片');
await page.screenshot({ path: path.join(out, 'order-4-filled.png'), fullPage: true });
await page.locator('#submit').tap(); await page.waitForTimeout(300);
await page.screenshot({ path: path.join(out, 'order-5-done.png'), fullPage: true });
console.log('done text:', (await page.locator('#done-view h1').innerText()));
const closed = await ctx.newPage(); await closed.goto(url('order.html', '?now=21:20&new=1')); await closed.screenshot({ path: path.join(out, 'order-6-closed.png') });
// owner side, same browser profile
const owner = await ctx.newPage(); await owner.setViewportSize({ width: 1024, height: 768 });
await owner.goto(url('owner.html', '?now=07:40&layout=matrix'));
await owner.fill('#q', '5678'); await owner.waitForTimeout(200);
await owner.screenshot({ path: path.join(out, 'owner-1-search.png') });
const rows = await owner.locator('.row').count(); console.log('rows matching 5678:', rows);
await owner.locator('.row button[data-act="pick"]').first().click(); await owner.waitForTimeout(200);
await owner.screenshot({ path: path.join(out, 'owner-2-picked.png') });
await owner.goto(url('owner.html', '?now=09:30')); await owner.screenshot({ path: path.join(out, 'owner-3-late.png') });
await owner.goto(url('owner.html', '?view=prep&now=05:10')); await owner.waitForTimeout(200);
console.log('toast total after order:', await owner.locator('.brow .total b').first().innerText(), '| slice chip:', await owner.locator('.slice').first().innerText());
console.log('errors:', errors.length, errors.slice(0, 3));
await browser.close();
